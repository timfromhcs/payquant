import os

# Create a small valid 32x32 ICO binary file for favicon.ico
ico_header = bytes([
    0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x20, 0x20,
    0x00, 0x00, 0x01, 0x00, 0x20, 0x00, 0x80, 0x04,
    0x00, 0x00, 0x16, 0x00, 0x00, 0x00
])

# Standard 32x32 RGBA bitmap payload
bmp_header = bytes([
    0x28, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00,
    0x40, 0x00, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
])

# Fill 32x32 pixels with Cyan/Violet gradient
pixel_data = bytearray()
for y in range(32):
    for x in range(32):
        # BGRA
        r = int(0 + (x / 32.0) * 157)
        g = int(242 - (y / 32.0) * 164)
        b = 254
        a = 255
        pixel_data.extend([b, g, r, a])

# Mask
mask_data = bytes([0x00] * 128)

ico_binary = ico_header + bmp_header + pixel_data + mask_data

for target_dir in ['site', 'doc']:
    filepath = os.path.join(target_dir, 'favicon.ico')
    with open(filepath, 'wb') as f:
        f.write(ico_binary)
    print(f"Created {filepath} ({len(ico_binary)} bytes)")
